#!/usr/bin/env python3
"""vehicle_seam_scan.py - THE VEHICLE SEAM GUARD (ours, 2026-11-20,
~/tcu_sweep/fork_seams_port.md; the fork-readiness audit
~/tcu_sweep/fork_readiness_audit.md §4.6 / §5).

Two checks:

  vehicle_seam_scan.py ids FIRMWARE_DIR [--only FILE ...]
      No firmware source OUTSIDE io/vehicle/ may name a vehicle-bus CAN ID in code.
      The vehicle IDs are the FCA receive table (io/vehicle/profile_fca.c), the FCA
      transmit set (io/vehicle/fca_tx_fields.h), the NISSAN skeleton's receive table
      (io/vehicle/profile_nissan.c, 9) and its two documented-TODO transmit IDs
      (io/vehicle/nissan_tx.h, 0x177 / 0x421, never sent), and the stock comm-monitor table
      (app/fr_cal.c fr_cal_rx — parsed read-only, plus a frozen 2026-11-20 snapshot in
      case its format changes). Sources are read with comments and string literals
      stripped; a hex literal of a vehicle ID is a hit when the same line has a CAN
      context (an .id / id field, CAN_BUS, can_frame, a *_rx_register call, an *_ID
      macro, ...), so register offsets and calibration constants that happen to equal
      an ID (0x120, 0x200, ...) do not trip it. The exceptions known today are in
      ALLOWLIST below, each with its reason. Also: plantdump/pd.c's DUMP_ID must equal
      DIAG_ID_PLANTDUMP of io/vehicle/diag_ids.h.
      Scope: the production firmware (app bsw safety io platform loader flasher
      plantdump plantflash include); the host tests (tests/) build FCA frames by design
      (audit §1.9; the injector io/vehicle/vehicle_inject.h is their way out).

  vehicle_seam_scan.py elf NM ELF [ELF ...]
      The TEST-ONLY injector (io/vehicle/vehicle_inject.c) must never be linked into an
      SH image: fails if any symbol named vehicle_inject* is in an ELF / object.

      Also: no file outside io/vehicle/ and bsw/com/ may #include "io/vehicle/fca_tx.h" or
      "bsw/com/com.h" (the transmit seam io/vehicle/vehicle_tx.h is the way in).

Exit 1 (and "vehicle seam guard violation") on any hit.
"""
import os
import re
import subprocess
import sys

DIRS = ("app", "bsw", "safety", "io", "platform", "loader", "flasher",
        "plantdump", "plantflash", "include")
SEAM_DIR = "io/vehicle/"          # the vehicle profile / transmit set live here

# Today's known exceptions (paths relative to FIRMWARE_DIR). Each one is a file that
# names vehicle CAN IDs ON PURPOSE; the fork replaces or re-binds it (audit §1.6).
ALLOWLIST = {
    # the read-only fault-reaction / gear-code shadow: the stock's FCA comm-monitor table
    # (53 entries, generated by tools/gen_fr_cal.py and byte-checked against the FCA
    # image) and its raw-frame matcher (D-FR-8). The fork needs a Nissan entry table
    # (audit §4.3). Also edited concurrently by the fault-chain port — not touched here.
    "app/fr_cal.c": "FCA comm-monitor table fr_cal_rx (stock data, D-FR-8)",
    "app/fr_cal.h": "FCA comm-monitor table declarations",
    "app/fr_shadow.c": "raw-frame matcher of the fault-chain shadow (D-FR-8)",
    "app/fr_shadow.h": "fault-chain shadow (comments / layout)",
    "app/fr_fm.c": "fault-chain shadow fault manager",
    "app/fr_hook.c": "raw-frame tap of the fault-chain shadow (D-FR-8)",
}

# CROSS-VEHICLE COLLISIONS (2026-11-20, the Nissan skeleton): 0x160 and 0x180 are IDs of BOTH vehicles
# (Nissan THROTTLE / ENGINE_RPM_ALT; FCA transfer case / engine temperature, both in the stock
# comm-monitor table fr_cal_rx). The ID set is a union, so a literal of either is a hit outside
# io/vehicle/; the one file that names them on purpose, app/fr_cal.c (FCA table, allowlisted
# below), names them as FCA entries only - on a Nissan build the fault shadow is FCA-only data
# and must be re-bound to a Nissan node map (audit §4.3) before it means anything there.

# frozen 2026-11-20 snapshot of fr_cal_rx's IDs (53 entries, 52 distinct; 0x200 on both buses)
FR_CAL_SNAPSHOT = [
    0x101, 0x102, 0x108, 0x10C, 0x10D, 0x112, 0x118, 0x11C, 0x120, 0x122, 0x134, 0x140,
    0x14B, 0x14C, 0x158, 0x160, 0x161, 0x180, 0x1AA, 0x1D0, 0x1F5, 0x200, 0x210, 0x212,
    0x271, 0x278, 0x29D, 0x2A0, 0x2A4, 0x2E0, 0x2E1, 0x2EA, 0x2F8, 0x2FA, 0x301, 0x308,
    0x310, 0x31F, 0x324, 0x32A, 0x330, 0x334, 0x381, 0x38A, 0x3E0, 0x3E4, 0x3E8, 0x3E9,
    0x3EA, 0x3EB, 0x3F5, 0x44C,
]

# a CAN context on the same (comment-stripped) line
CAN_CTX = re.compile(
    r"(\.id\b|->id\b|\bid\s*[=!<>]=?|\bid\s*,|\bcan_|\bCAN_BUS|can_frame|_rx_register|"
    r"\b[A-Z0-9_]*_ID\b|\bmsg_id\b|\bcan_id\b|"
    # a table row whose first two members are an 11-bit ID and a bus (CAN_BUSn or 1u/2u),
    # as profile_fca.c's com_rx_cfg_t and fr_cal.c's fr_cal_rx_t rows are written
    r"\{\s*0[xX][0-9A-Fa-f]{1,3}[uU]?\s*,\s*(CAN_BUS\d|[12][uU]?)\s*,|"
    # an X-macro message row, as fca_tx_fields.h's X(M_037, 0x037u, ...)
    r"\bX\(\s*M_\w+\s*,)")
HEX = re.compile(r"\b0[xX]([0-9A-Fa-f]+)[uUlL]*\b")


def strip(t):
    t = re.sub(r"/\*.*?\*/", lambda m: "\n" * m.group(0).count("\n"), t, flags=re.S)
    t = re.sub(r"//[^\n]*", " ", t)
    return re.sub(r'"(\\.|[^"\\\n])*"', '""', t)


# the transmit seam (io/vehicle/vehicle_tx.h) and the profile interface are the ONLY way into the
# vehicle layer: nothing outside io/vehicle/ (the com layer bsw/com/ itself excepted) may include
# the FCA transmit set or the com layer's header
INCLUDE_RULE = re.compile(r'^\s*#\s*include\s*"([^"]*/)?(fca_tx|com)\.h"', re.M)
INCLUDE_EXEMPT = ("io/vehicle/", "bsw/com/")


def strip_comments(t):
    t = re.sub(r"/\*.*?\*/", lambda m: "\n" * m.group(0).count("\n"), t, flags=re.S)
    return re.sub(r"//[^\n]*", " ", t)


def vehicle_ids(root):
    ids = set(FR_CAL_SNAPSHOT)
    src = open(os.path.join(root, "io/vehicle/profile_fca.c")).read()
    rx = {int(h, 16) for h in re.findall(r"\{\s*0x([0-9A-Fa-f]+)u,\s*CAN_BUS", src)}
    tx = {int(h, 16) for h in re.findall(
        r"X\(M_[0-9A-Fa-f]+,\s*0x([0-9A-Fa-f]+)u",
        open(os.path.join(root, "io/vehicle/fca_tx_fields.h")).read())}
    if len(rx) != 10 or len(tx) != 8:
        sys.exit(f"vehicle seam guard violation: could not parse the FCA tables "
                 f"(rx {len(rx)}/10, tx {len(tx)}/8)")
    ids |= rx | tx
    # the NISSAN profile: nine receive rows; the transmit set 0x174 / 0x176 / 0x177 / 0x560 (2026-11-23)
    # and the never-sent gear indicator 0x421
    nrx = {int(h, 16) for h in re.findall(
        r"\{\s*0x([0-9A-Fa-f]+)u,\s*CAN_BUS",
        open(os.path.join(root, "io/vehicle/profile_nissan.c")).read())}
    ntx = {int(h, 16) for h in re.findall(
        r"#define\s+NISSAN_TX_(?:TODO_)?ID_\w+\s+0x([0-9A-Fa-f]+)u",
        open(os.path.join(root, "io/vehicle/nissan_tx.h")).read())}
    if len(nrx) != 9 or len(ntx) != 5:
        sys.exit(f"vehicle seam guard violation: could not parse the Nissan tables "
                 f"(rx {len(nrx)}/9, tx {len(ntx)}/5)")
    ids |= nrx | ntx
    try:
        s = open(os.path.join(root, "app/fr_cal.c")).read()
        i = s.index("fr_cal_rx[")
        j = s.index("};", i)
        ids |= {int(h, 16) for h in re.findall(r"\{\s*0x([0-9A-Fa-f]+)u,\s*\du,", s[i:j])}
    except (OSError, ValueError):
        pass                       # the frozen snapshot covers it
    return ids


def scan_ids(argv):
    root = os.path.abspath(argv[0])
    ids = vehicle_ids(root)
    if "--only" in argv:
        files = [os.path.abspath(f) for f in argv[argv.index("--only") + 1:]]
        allow = {}
    else:
        allow = ALLOWLIST
        files = []
        for d in DIRS:
            for dp, _, fn in os.walk(os.path.join(root, d)):
                for f in fn:
                    if f.endswith((".c", ".h", ".S")):
                        files.append(os.path.join(dp, f))
    hits = []
    for f in sorted(files):
        rel = os.path.relpath(f, root).replace(os.sep, "/")
        if "--only" not in argv and (rel.startswith(SEAM_DIR) or rel in allow):
            continue
        raw = open(f, errors="replace").read()
        if "--only" in argv or not rel.startswith(INCLUDE_EXEMPT):
            for m in INCLUDE_RULE.finditer(strip_comments(raw)):
                n = strip_comments(raw)[:m.end()].count("\n") + 1
                hits.append(f"{rel}:{n}: includes the vehicle layer's own header "
                            f"({m.group(2)}.h): use io/vehicle/vehicle.h / vehicle_tx.h")
        text = strip(raw)
        for n, line in enumerate(text.split("\n"), 1):
            if not CAN_CTX.search(line):
                continue
            for m in HEX.finditer(line):
                if int(m.group(1), 16) in ids:
                    hits.append(f"{rel}:{n}: vehicle CAN ID 0x{int(m.group(1), 16):03X}: {line.strip()}")
    # the plant dumper builds standalone (no include path): its ID must match the header
    if "--only" not in argv:
        pd = open(os.path.join(root, "plantdump/pd.c")).read()
        dh = open(os.path.join(root, "io/vehicle/diag_ids.h")).read()
        a = re.search(r"#define\s+DUMP_ID\s+0x([0-9A-Fa-f]+)", pd)
        b = re.search(r"#define\s+DIAG_ID_PLANTDUMP\s+0x([0-9A-Fa-f]+)", dh)
        if not a or not b or int(a.group(1), 16) != int(b.group(1), 16):
            hits.append("plantdump/pd.c DUMP_ID != io/vehicle/diag_ids.h DIAG_ID_PLANTDUMP")
    for h in hits:
        print(h)
    if hits:
        print(f"vehicle seam guard violation: {len(hits)} hit(s)")
        return 1
    print(f"vehicle seam scan: {len(files)} files, {len(ids)} vehicle IDs, "
          f"{len(allow)} allowlisted, clean")
    return 0


def scan_elf(argv):
    nm = argv[0]
    bad = []
    for e in argv[1:]:
        out = subprocess.run([nm, e], capture_output=True, text=True, check=True).stdout
        bad += [f"{e}: {l.strip()}" for l in out.splitlines() if re.search(r"\b_?vehicle_inject", l)]
    for b in bad:
        print(b)
    if bad:
        print("vehicle seam guard violation: the test-only injector is linked")
        return 1
    print(f"vehicle seam elf scan: {len(argv) - 1} file(s), no injector")
    return 0


def main():
    if len(sys.argv) < 3 or sys.argv[1] not in ("ids", "elf"):
        sys.exit(__doc__)
    return scan_ids(sys.argv[2:]) if sys.argv[1] == "ids" else scan_elf(sys.argv[2:])


if __name__ == "__main__":
    sys.exit(main())
