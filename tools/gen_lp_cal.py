#!/usr/bin/env python3
"""gen_lp_cal.py - writes app/lp_cal.c: the stock constants the line-pressure /
torque-intervention shadows (app/lp_shadow.c, app/ti_shadow.c) read from
addresses BELOW 0x80000 (our application overwrites that region: the cal pointer
table 0x5CFD8, the gear-map pointer cells, the shift-type index tables, the
per-unit EOL curves 0xE108 / 0xE170). Everything at 0x80000 and above is read
in place (app/cal_inplace.h). Usage: gen_lp_cal.py IMAGE OUT.c
The host test `lp_cal_bytes` re-derives every table from the image and compares."""
import struct
import sys

img = open(sys.argv[1], 'rb').read()


def u32(a):
    return struct.unpack('>I', img[a:a + 4])[0]


def u16(a):
    return struct.unpack('>H', img[a:a + 2])[0]


def s16(a):
    return struct.unpack('>h', img[a:a + 2])[0]


out = []
w = out.append
w('/* lp_cal.c - GENERATED by tools/gen_lp_cal.py from the stock image (do not edit).\n'
  ' * The stock calibration this shadow pair reads from BELOW 0x80000. */\n')
w('#include "app/lp_cal.h"\n')

# the cal pointer table 0x5CFD8: 48 words (cal + 4 * i)
w('const uint32_t LP_CALP[LP_CALP_N] = {')
w('    ' + ', '.join('0x%06Xu' % u32(0x5CFD8 + 4 * i) for i in range(48)))
w('};\n')

# gear maps: *(*(0x5CE3C + 8 idx + 0)) variant 0; the reason-0x0C demand cell (0 = none)
maps = []
hot = []
for idx in range(9):
    p = u32(0x5CE3C + 8 * idx)
    maps.append(u32(p))
    q = u32(p + 4)
    hot.append(0 if q == p else q)
w('const uint32_t LP_MAP[9] = { ' + ', '.join('0x%06Xu' % m for m in maps) + ' };')
w('const uint32_t LP_HOT[9] = { ' + ', '.join('0x%06Xu' % h for h in hot) + ' };\n')

# 0x51DE0: u32 [idx] -> map index
w('const uint8_t LP_G51DE0[10] = { ' + ', '.join(str(u32(0x51DE0 + 4 * i)) for i in range(10)) + ' };\n')

# shift-type index tables 0x51E08 (up, 9 x 9) / 0x51F4C (down, 9 x 9), and the demand cells
w('const uint8_t LP_UPIDX[81] = { ' + ', '.join(str(u32(0x51E08 + 4 * i)) for i in range(81)) + ' };')
w('const uint8_t LP_DNIDX[81] = { ' + ', '.join(str(u32(0x51F4C + 4 * i)) for i in range(81)) + ' };')
up = []
for i in range(7):
    c = u32(0x5CEC0 + 8 * i)
    up += [u32(c), u32(c + 4)]
w('const uint32_t LP_UPPTR[14] = { ' + ', '.join('0x%06Xu' % x for x in up) + ' };')
dn = [u32(u32(0x5CF44 + 8 * i)) if False else u32(0x5CF44 + 8 * i) for i in range(18)]
dn = []
for i in range(18):
    c = u32(0x5CF44 + 8 * i)
    dn.append(u32(c))
w('const uint32_t LP_DNPTR[18] = { ' + ', '.join('0x%06Xu' % x for x in dn) + ' };\n')

# the per-unit EOL curves (flash 0xE108 Sys curve, 0xE170 NO temperature map)
n = u32(0xE108)
w('const uint16_t LP_E108[1 + 2 * 12] = { %d, ' % n +
  ', '.join(str(u16(0xE108 + 4 + 2 * i)) for i in range(2 * n)) + ' };')
nx, ny = u32(0xE170), u32(0xE170 + 4)
cnt = nx + ny + nx * ny
w('const int16_t LP_E170[2 + %d] = { %d, %d, ' % (cnt, nx, ny) +
  ', '.join(str(s16(0xE170 + 8 + 2 * i)) for i in range(cnt)) + ' };\n')

# TI: class by BD16 (0x634D6) and the phase table 0x51C6C (7 rows x 3)
w('const uint8_t LP_TI_CLASS[8] = { ' + ', '.join(str(img[0x634D6 + i]) for i in range(8)) + ' };')
w('const uint8_t LP_TI_PHASE[24] = { ' + ', '.join(str(img[0x51C6C + i]) for i in range(24)) + ' };')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print('wrote', sys.argv[2], 'E108 n=%d E170 %dx%d' % (n, nx, ny))
