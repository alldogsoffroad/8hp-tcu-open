#!/usr/bin/env python3
"""gen_cal_golden.py — the golden digests of the shadows' IN-PLACE calibration views
(firmware/app/cal_inplace.h CAL_IP_LIST): per object the stock address, length and the
FNV-1a (32 bit) of its stock bytes, emitted as firmware/tests/unit/cal_inplace_golden.h.

The host test test_cal_inplace recomputes every digest through the view the shadows use
(app/cal_inplace.h) and compares: a changed address, a wrong length, a wrong image, or
an endianness error in an accessor fails. The digests are of the STOCK IMAGE bytes (the
bytes the former generated copies were byte-checked against).

usage: gen_cal_golden.py <stock image> <firmware/app/cal_inplace.h> <out .h>
"""
import re
import sys


def fnv1a(b):
    h = 0x811C9DC5
    for x in b:
        h = ((h ^ x) * 0x01000193) & 0xFFFFFFFF
    return h


def main():
    img = open(sys.argv[1], 'rb').read()
    hdr = open(sys.argv[2]).read()
    defs = {}
    for m in re.finditer(r'^#define\s+(CAL_[A-Z0-9_]+)\s+(.+?)\s*(?:/\*.*)?$', hdr, re.M):
        defs[m.group(1)] = m.group(2).strip()

    def ev(expr):
        expr = re.sub(r'\b(0x[0-9A-Fa-f]+|\d+)[uU]\b', r'\1', expr)
        for _ in range(8):
            expr = re.sub(r'\bCAL_[A-Z0-9_]+\b', lambda mm: '(' + re.sub(r'\b(0x[0-9A-Fa-f]+|\d+)[uU]\b', r'\1', defs[mm.group(0)]) + ')', expr)
        return eval(expr)

    lst = re.search(r'#define CAL_IP_LIST\(X\)(.*?)\n\n', hdr, re.S).group(1)
    ents = re.findall(r'X\((\w+),\s*([^,]+),\s*([^)]*)\)', lst)
    assert len(ents) >= 25, len(ents)
    o = ['/* cal_inplace_golden.h — GENERATED by tools/gen_cal_golden.py; do not edit. The stock addresses, lengths and',
         ' * FNV-1a digests of the in-place calibration objects (app/cal_inplace.h CAL_IP_LIST), same order. */',
         '#ifndef TCU_CAL_INPLACE_GOLDEN_H',
         '#define TCU_CAL_INPLACE_GOLDEN_H',
         '#include <stdint.h>',
         'typedef struct { const char *name; uint32_t addr, len, fnv; } cal_golden_t;',
         'static const cal_golden_t cal_golden[] = {']
    for name, a, n in ents:
        addr, ln = ev(a), ev(n)
        assert addr >= 0x80000 and addr + ln <= len(img), (name, hex(addr), ln)
        o.append('    { "%s", 0x%06Xu, %du, 0x%08Xu },' % (name, addr, ln, fnv1a(img[addr:addr + ln])))
    o.append('};')
    o.append('#endif')
    open(sys.argv[3], 'w').write('\n'.join(o) + '\n')
    print('%d objects' % len(ents))


if __name__ == '__main__':
    main()
