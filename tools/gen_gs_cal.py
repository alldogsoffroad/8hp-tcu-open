#!/usr/bin/env python3
"""gen_gs_cal.py — the garage-engagement SHADOW: emit firmware/app/gs_cal.c, the
const copies of the stock flash bytes the read-only shadow of the garage
engagement (app/gs_shadow.c) reads by their STOCK flash address
(gs_fill.c gsf_fl*, through rq_fill.c's RQF_FL_EXTRA_LOOKUP hook).

Roots (each justified in app/gs_shadow.c; ~/tcu_sweep/garage_shadow_port.md):
  0x63176  the engagement phase table (10 steps x 6 types, step-major)
  0x6312E  the role tables 0x6312F / 0x63139 / 0x63143 (gear -1..8)
  0x6354C  the power-flow request table 0x103F56
  0x63445  the direction table 0xCFFDE (range -> AE28)
  0x505A4  the holder table (0xDC1E2), 0x63122 / 0x63128 its overrides
  0x5DD90 / 0x5DDB8 / 0x5DDE0  gear -> cal index (0x10D130)
  0x5ADE0 / 0x590EC / 0x57354  index -> blk58 / blk5C / blk60 pointers
  0x5DE08  element -> RAM pointer cell (sub +0x64)
  0x56F98 / 0x5713C  the blocks behind RAM cells 0xFFF84D44 / 0xFFF84D48
  0x57474 + 0x40.e  the element blocks behind 0xFFF84D4C..0xFFF84D5C
  blk58 / blk5C / blk60 for the cal indices 0 (R) and 1 (1st)
and one level of every word in those blocks that points into flash (the maps
and scalar cells), each copied over its header-derived size (capped).

The host test gs_cal_bytes compares every blob with the image byte for byte.

usage: gen_gs_cal.py <stock image> <out .c>
"""
import struct
import sys

LO, HI = 0x40000, 0x200000


def main():
    img = open(sys.argv[1], 'rb').read()
    u32 = lambda a: struct.unpack('>I', img[a:a + 4])[0]

    ranges = []

    def add(a, n):
        ranges.append((a, min(a + n, len(img))))

    def map_size(t):
        """a conservative copy length for a map / scalar object at t"""
        nx = u32(t)
        ny = u32(t + 4)
        if 1 <= nx <= 40 and 1 <= ny <= 40:
            n = 8 + 2 * (nx + ny + nx * ny)          # 2-D s16 (largest 2-D form)
            n = max(n, 4 + 4 * nx)
        elif 1 <= nx <= 64:
            n = 4 + 4 * nx                            # 1-D u16 / s16 (u8 is smaller)
        else:
            n = 0x10                                  # a scalar cell
        return min(n, 0x200)

    def follow(blk, n):
        add(blk, n)
        for off in range(0, n, 4):
            w = u32(blk + off)
            if LO <= w < HI:
                add(w, map_size(w))

    add(0x63176, 0x42)          # phase table (+ the 0xFF tail)
    add(0x6312E, 0x20)          # role tables
    add(0x63122, 0x0C)          # holder overrides 0x63122 / 0x63128
    add(0x505A4, 0x78)          # the holder table (2 blocks x 10 rows x 6)
    add(0x6354C, 0x09)
    add(0x63445, 0x09)
    for t in (0x5DD90, 0x5DDB8, 0x5DDE0):
        add(t, 0x28)
    for t in (0x5ADE0, 0x590EC, 0x57354):
        add(t, 0x48)
    add(0x5DE08, 0x18)
    follow(0x56F98, 0x80)
    follow(0x5713C, 0x80)
    for e in range(5):
        follow(0x57474 + 0x40 * e, 0x40)
    for idx in (0, 1):
        follow(u32(0x5ADE0 + 8 * idx), 0xFC)   # blk58
        follow(u32(0x590EC + 8 * idx), 0x38)   # blk5C
        follow(u32(0x57354 + 8 * idx), 0x10)   # blk60

    # merge
    ranges.sort()
    merged = []
    for a, b in ranges:
        if merged and a <= merged[-1][1] + 8:
            merged[-1] = (merged[-1][0], max(merged[-1][1], b))
        else:
            merged.append((a, b))

    out = []
    out.append('/* gs_cal.c — GENERATED by tools/gen_gs_cal.py from the pristine stock image')
    out.append(' * (260924131233 1034420267_IFla.bin). Do not edit: regenerate.')
    out.append(' * Const copies of the stock flash ranges the READ-ONLY garage-engagement')
    out.append(' * shadow reads (app/gs_shadow.c), by flash address. The host test')
    out.append(' * gs_cal_bytes compares every byte with the image. */')
    out.append('#include "app/gs_cal.h"')
    out.append('')
    out.append('#if !defined(TCU_RAM_APP)')
    names = []
    for (a, b) in merged:
        n = 'GS_FL_%06X' % a
        names.append((n, a, b))
        out.append('static const uint8_t %s[0x%X] = {' % (n, b - a))
        data = img[a:b]
        for i in range(0, len(data), 16):
            out.append('    ' + ', '.join('0x%02X' % x for x in data[i:i + 16]) + ',')
        out.append('};')
    out.append('')
    out.append('const gs_blob_t GS_BLOBS[GS_NBLOBS] = {')
    for (n, a, b) in names:
        out.append('    { 0x%08Xu, 0x%Xu, %s },' % (a, b - a, n))
    out.append('};')
    out.append('')
    out.append('const uint8_t *gs_cal_lookup(uint32_t a, uint32_t n)')
    out.append('{')
    out.append('    for (uint32_t i = 0u; i < GS_NBLOBS; i++) {')
    out.append('        const gs_blob_t *b = &GS_BLOBS[i];')
    out.append('        if (a >= b->addr && a - b->addr + n <= b->len) {')
    out.append('            return &b->data[a - b->addr];')
    out.append('        }')
    out.append('    }')
    out.append('    return 0;')
    out.append('}')
    out.append('#endif')
    out.append('')
    open(sys.argv[2], 'w').write('\n'.join(out))
    print('GS_NBLOBS %d, bytes: %d' % (len(merged), sum(b - a for a, b in merged)))


if __name__ == '__main__':
    main()
