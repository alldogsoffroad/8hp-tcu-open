#!/usr/bin/env python3
"""gen_ti_cal.py - writes app/ti_cal.c: the stock constants the torque-intervention
shadow (app/ti_shadow.c) reads from addresses BELOW 0xA0000, where our application may
overwrite the stock image: the per-type index tables (0x50804 .. 0x51B28 + 81 words each)
and the VARIANT-0 words of the per-type calibration blocks (0x54FE0 .. 0x56E0C tables;
each block is an array of pointers into the stock calibration at 0x19F000 .. 0x1FF200,
which the shadow reads IN PLACE through app/cal_inplace.h). A block word equal to the
block's own address (the stock's "no map" marker) is stored as 0. Usage: gen_ti_cal.py IMAGE OUT.c
The host test `ti_cal_bytes` re-derives every table from the image and compares."""
import struct
import sys

img = open(sys.argv[1], 'rb').read()


def u32(a):
    return struct.unpack('>I', img[a:a + 4])[0]


def s32(a):
    return struct.unpack('>i', img[a:a + 4])[0]


CAL_MIN = 0xA0000          # every non-zero block word must point at or above this (in-place)
out = []
w = out.append
w('/* ti_cal.c - GENERATED by tools/gen_ti_cal.py from the stock image (do not edit).\n'
  ' * The stock calibration indexes and variant-0 block pointers of the torque-intervention\n'
  ' * shadow, from BELOW 0xA0000. A block word 0 = the stock\'s self-pointer ("no map"). */\n')
w('#include "app/ti_cal.h"\n')


def idx_table(addr, n, limit):
    vals = []
    for i in range(n):
        v = s32(addr + 4 * i)
        vals.append(0xFF if (v < 0 or v >= limit) else v)
    return vals


def arr8(name, vals):
    return 'const uint8_t %s[%d] = { %s };' % (name, len(vals), ', '.join(str(v) for v in vals))


w(arr8('TI_IDX_GEAR', idx_table(0x50804, 10, 9)))
w(arr8('TI_IDX_UP', idx_table(0x5082C, 81, 7)))
w(arr8('TI_IDX_DN4', idx_table(0x50970, 81, 7)))
w(arr8('TI_IDX_DN', idx_table(0x50AB4, 81, 18)))
for nm, tabs, lim in (('TI_IDX_584', (0x50BF8, 0x50D3C, 0x50E80, 0x50FC4, 0x51108), 35),
                      ('TI_IDX_5814', (0x5124C, 0x51390, 0x514D4, 0x51618), 28),
                      ('TI_IDX_5892', (0x5175C, 0x518A0, 0x519E4, 0x51B28), 61)):
    w('const uint8_t %s[%d][81] = {' % (nm, len(tabs)))
    for t in tabs:
        w('    { %s },' % ', '.join(str(v) for v in idx_table(t, 81, lim)))
    w('};')
w('')


def blocks(nm, tab, n, nw):
    w('const uint32_t %s[%d][%d] = {' % (nm, n, nw))
    for i in range(n):
        b = u32(tab + 8 * i)           # the variant-0 block (+4 = variant 1)
        words = []
        for k in range(nw):
            v = u32(b + 4 * k)
            if v == b:
                v = 0
            elif v < CAL_MIN:
                sys.exit('%s[%d][%d] = 0x%X below 0x%X' % (nm, i, k, v, CAL_MIN))
            words.append(v)
        w('    { %s },' % ', '.join('0x%06Xu' % v if v else '0u' for v in words))
    w('};')


blocks('TI_B_GEAR', 0x55868, 9, 13)
blocks('TI_B_UP', 0x55D6C, 7, 13)
blocks('TI_B_584', 0x55AE4, 35, 4)
blocks('TI_B_5814', 0x55440, 28, 10)
blocks('TI_B_DN', 0x56E0C, 18, 4)
blocks('TI_B_DN4', 0x55658, 7, 9)
blocks('TI_B_5892', 0x56B00, 61, 14)
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print('wrote', sys.argv[2])
