#!/usr/bin/env python3
"""gen_gp_cal.py — THE GEAR-PAIR SHIFT-ENGINE SHADOW: emit firmware/app/gp_cal.c,
the typed const copies of the stock tables the read-only gear-pair shadow
(app/gp_shadow.c) uses — ONLY those whose stock source lies BELOW 0x80000 (our app
overwrites that region). The tables at 0x80000 and above (the f8 arrays, the four
condition windows, the temperature / BD1B threshold bytes, the override map, the sync
band) are read IN PLACE (app/cal_inplace.h, 2026-11-20); this script only ASSERTS
their addresses against the pointer chains. Every object carries its stock flash address; the host
test gp_cal_bytes (tests/unit/test_gp_shadow.c --cal) re-reads the image and
compares value for value.

Roots (~/tcu_sweep/shift_engine_gearpair_decode.md §1.2 / §1.6 / §1.4 and
~/tcu_sweep/gp_shadow_port.md; each address read in the bytes):
  0x5061C  the on-coming element of a gear pair, t[(from+1) + (to+1)*10]
           (0xDC198 via 0xB852A, pool 0xDC3DC), element 1..5 = A..E
  0x50680  the off-going element, same index (0xDC1AE via 0xB853C, pool 0xDC3E0)
  0x6315C  BD17 = t[BD1E*3 + BD16] (0xED988, pool 0xEDB44)
  0x5EC24  the on-coming phase sequence, phase = t[step*3 + type] (0x113D0A,
           pool 0x113D98), steps 0..11
  0x63555  the off-going phase sequence, phase = t[step*3 + type] (0x110ADE,
           pool 0x110B84), steps 0..12
  0x4FAA4  the gear ratios x1000 (0xD7C8C: *0xFFF84B2C, gs_engine.c)
  *(0x5713C + 0xB0) = 0x1FF1F6  the synchronisation band, rpm (0xEB4A4 /
           0x117F48, gs_engine.c)
The direct-shift type 0x4F9DC and the kind 0x4FA40 are sm_cal_gtype /
sm_cal_gkind (app/sm_cal.c, already byte-checked).

2026-11-20 (the stand-in retirements, ~/tcu_sweep/shift_class_counters_decode.md
sections 1..6; every pool / pointer chain asserted against the bytes below):
  *(0x5713C + 0x2C / 0x34)  the shift-character arrays f8 = t[0x89CF4]
           (0xEC362; {u32 n; u8 v[]}), down 0x1B607C / up 0x1B6094
  *(0x5713C + 0xF0..0xFC / 0xE0..0xEC / 0xD0..0xDC)  the 0xEC40E / 0xEC4D8 /
           0xEC578 / 0xEC614 condition windows: 10 x 10 tables (output speed
           >= , torque lower <, < torque upper), index (to+1)*10 + (from+1)
           (0xB6D14 / 0xB6CE8: {u32 ncols; u32 nrows; s16 data[]})
  *(0x5713C + 0x7C..0xA8)   the temperature-byte windows, the 0xA1032 gate and
           the 0xA8 byte; *(0x5713C + 0xB8..0xC8) the BD1B thresholds (0xEC7CC /
           0xEC6A6); *(0x5713C + 0x154 / 0x158) the 0x117B4A override's pedal
           byte and the turbine -> torque map; 0x19B03C the override's f8
           array (0xD02EC)
  class-1 rows (2->1 and 3->2 down-shifts, variant 0): on-coming lock count /
           phase-1 delay / phase-0x0A duration (blocks 0x5C84C / 0x5C894 via
           0x5F014 -> 0x5CD5C), off-going phase-0x0B / 0x0F durations and the
           phase-1 committed duration (blocks 0x596E4 / 0x59718 via 0x5E984 ->
           0x59E34): index = the shift's FROM gear (verified here: 0x5F014[2]
           = 0, [3] = 1; 0x5E984[2] = 7, [3] = 8)

usage: gen_gp_cal.py <stock image> <out .c> <NUP> <out gp_cal_ph.h>
"""
import struct
import sys

T_ON, T_OFF, T_BD17, T_ONSEQ, T_OFFSEQ, T_RATIO = 0x5061C, 0x50680, 0x6315C, 0x5EC24, 0x63555, 0x4FAA4
N_ONSEQ, N_OFFSEQ = 12 * 3, 13 * 3


def fnv1a(b):
    h = 0x811C9DC5
    for x in b:
        h = ((h ^ x) * 0x01000193) & 0xFFFFFFFF
    return h


def main():
    img = open(sys.argv[1], 'rb').read()
    u32 = lambda a: struct.unpack('>I', img[a:a + 4])[0]
    u16 = lambda a: struct.unpack('>H', img[a:a + 2])[0]
    # the pools (each read in the bytes; the host test re-checks the values)
    assert u32(0xDC3DC) == T_ON and u32(0xDC3E0) == T_OFF
    assert u32(0xEDB44) == T_BD17
    assert u32(0x113D98) == T_ONSEQ and u32(0x110B84) == T_OFFSEQ
    thr_at = u32(0x5713C + 0xB0)
    assert thr_at == 0x1FF1F6, hex(thr_at)

    o = []
    o.append('/* gp_cal.c — GENERATED by tools/gen_gp_cal.py from the stock image; do not edit.')
    o.append(' * The gear-pair shadow\'s table copies (app/gp_cal.h): ONLY the tables whose stock source is')
    o.append(' * below 0x80000 (our app overwrites it); the rest is read in place (app/cal_inplace.h).')
    o.append(' * Byte-checked by tests/unit/test_gp_shadow.c --cal (ctest gp_cal_bytes) and test_cal_inplace. */')
    o.append('#include "app/gp_cal.h"')
    o.append('#include "app/gp_cal_ph.h"')
    o.append('')
    o.append('/* the mutation negative (ctest gp_shadow_neg_TABLE): the 1->2 on-coming element,')
    o.append(' * t[(1+1) + (2+1)*10] = 5 (E) -> 4 (D) — the pre-select / commit check must fail */')
    o.append('#if defined(GP_NEG_TABLE)')
    o.append('#define GP_NEG_E(v) ((v) - 1u)')
    o.append('#else')
    o.append('#define GP_NEG_E(v) (v)')
    o.append('#endif')
    o.append('')

    def u8arr(name, addr, n, comment, neg=None):
        vals = ['%du' % b for b in img[addr:addr + n]]
        if neg is not None:
            i, macro, want = neg
            assert img[addr + i] == want, (name, i, img[addr + i])
            vals[i] = '%s(%du)' % (macro, want)
        o.append('/* %s */' % comment)
        o.append('const uint8_t %s[%d] = {' % (name, n))
        for i in range(0, n, 12):
            o.append('    %s,' % ', '.join(vals[i:i + 12]))
        o.append('};')
        o.append('')

    u8arr('gp_cal_on', T_ON, 100, '0x5061C: the on-coming element t[(from+1) + (to+1)*10] (0xDC198)',
          ((1 + 1) + (2 + 1) * 10, 'GP_NEG_E', 5))
    u8arr('gp_cal_off', T_OFF, 100, '0x50680: the off-going element t[(from+1) + (to+1)*10] (0xDC1AE)')
    u8arr('gp_cal_bd17', T_BD17, 9, '0x6315C: BD17 = t[BD1E*3 + BD16] (0xED988)')
    u8arr('gp_cal_onseq', T_ONSEQ, N_ONSEQ, '0x5EC24: the on-coming phase t[step*3 + type] (0x113D0A)')
    u8arr('gp_cal_offseq', T_OFFSEQ, N_OFFSEQ, '0x63555: the off-going phase t[step*3 + type] (0x110ADE)')
    o.append('/* 0x4FAA4: the gear ratios x1000, gear -1..8 (0xD7C8C) */')
    o.append('const uint16_t gp_cal_ratio[10] = { %s };' % ', '.join('%du' % u16(T_RATIO + 2 * i) for i in range(10)))
    o.append('')
    # -- from here to the class-1 rows: tables at 0x80000 and above, READ IN PLACE
    # (app/cal_inplace.h); the emission is discarded, the address asserts stay --
    o_main = o
    o = []
    assert thr_at == 0x1FF1F6
    o.append('/* *(0x5713C + 0xB0) = 0x1FF1F6: the synchronisation band, rpm (0x117F48) */')
    o.append('const uint16_t gp_cal_sync_thr = %du;' % u16(thr_at))
    o.append('')
    # ---- 2026-11-20 additions -------------------------------------------------
    o.append('/* the mutation negative (ctest gp_shadow_neg_CLASS): the down-shift f8 array t[1] = 1 -> 0:')
    o.append(' * 0xEC20A then never accepts a downshift window, every kind stays 2 (class 0) */')
    o.append('#if defined(GP_NEG_CLASS)')
    o.append('#define GP_NEG_F(v) ((v) - 1u)')
    o.append('#else')
    o.append('#define GP_NEG_F(v) (v)')
    o.append('#endif')
    o.append('')
    s16 = lambda a: struct.unpack('>h', img[a:a + 2])[0]
    BASE = 0x5713C

    def ptr(off):
        return u32(BASE + off)

    def arr_u8(name, p, comment, mutate=None):
        n = u32(p)
        assert n == 5, (name, n)
        vals = ['%du' % b for b in img[p + 4:p + 4 + n]]
        if mutate is not None:
            i, want = mutate
            assert img[p + 4 + i] == want
            vals[i] = 'GP_NEG_F(%du)' % want
        o.append('/* %s */' % comment)
        o.append('const uint8_t %s[5] = { %s };' % (name, ', '.join(vals)))
        o.append('')

    assert ptr(0x2C) == 0x1B607C and ptr(0x34) == 0x1B6094
    arr_u8('gp_cal_f8_dn', ptr(0x2C), '*(0x5713C + 0x2C) = 0x1B607C: f8 = t[0x89CF4] for the types 3 / 4 (0xEC362)',
           (1, 1))
    arr_u8('gp_cal_f8_up', ptr(0x34), '*(0x5713C + 0x34) = 0x1B6094: f8 = t[0x89CF4] for the types 1 / 2 (0xEC362)')
    arr_u8('gp_cal_f8_ov', 0x19B03C, "0x19B03C: the 0x117B4A override's f8 = t[0x89CF4] (0xD02EC via 0xB6B28)")

    FUNCS = [('ec40e', 0xF0, 0xE0, 0xD0), ('ec4d8', 0xF4, 0xE4, 0xD4), ('ec578', 0xF8, 0xE8, 0xD8),
             ('ec614', 0xFC, 0xEC, 0xDC)]
    outs, los, his = [], [], []
    for nm, oo, lo, hi in FUNCS:
        for off, lst, uns in ((oo, outs, True), (lo, los, False), (hi, his, False)):
            p = ptr(off)
            assert u32(p) == 10 and u32(p + 4) == 10, (nm, hex(off))
            lst.append([(u16(p + 8 + 2 * i) if uns else s16(p + 8 + 2 * i)) for i in range(100)])
    o.append('/* the four condition windows (0xEC40E / 0xEC4D8 / 0xEC578 / 0xEC614), tables')
    o.append(' * *(0x5713C + {0xF0,0xF4,0xF8,0xFC}) output speed >=, {0xE0,0xE4,0xE8,0xEC} torque lower <,')
    o.append(' * {0xD0,0xD4,0xD8,0xDC} < torque upper; 10 x 10, index (to+1)*10 + (from+1) */')
    for nm, lst, ty in (('gp_cal_win_out', outs, 'uint16_t'), ('gp_cal_win_lo', los, 'int16_t'),
                        ('gp_cal_win_hi', his, 'int16_t')):
        o.append('const %s %s[4][100] = {' % (ty, nm))
        for t in lst:
            o.append('    { %s },' % ', '.join('%d' % v for v in t))
        o.append('};')
        o.append('')
    tmp_offs = [0x80, 0x84, 0x88, 0x8C, 0x90, 0x94, 0x98, 0x9C, 0xA0, 0xA4]
    tmp = [img[ptr(x)] for x in tmp_offs]
    assert tmp == [170, 40, 40, 170, 40, 40, 150, 70, 185, 40], tmp
    o.append('/* the temperature-byte windows: 0xEC40E max/up-min/down-min (+0x80/84/88), 0xEC4D8 (+0x8C/90/94),')
    o.append(' * 0xEC578 max/min (+0x98/0x9C), 0xEC614 max/min (+0xA0/0xA4) */')
    o.append('const uint8_t gp_cal_tmp[10] = { %s };' % ', '.join('%du' % v for v in tmp))
    o.append('')
    o.append('/* *(0x5713C + 0x7C) the 0xA1032 gate byte, *(+0xA8) the "BD16 != 2" byte (0x1180BE) */')
    o.append('const uint8_t gp_cal_k7c = %du;' % img[ptr(0x7C)])
    o.append('const uint8_t gp_cal_ka8 = %du;' % img[ptr(0xA8)])
    o.append('')
    thr = [s16(ptr(x)) for x in (0xB8, 0xBC, 0xC0, 0xC4, 0xC8)]
    o.append('/* the BD1B thresholds *(0x5713C + 0xB8 / 0xBC / 0xC0 / 0xC4) (0xEC7CC) and the turbine one (+0xC8) */')
    o.append('const int16_t gp_cal_thr[5] = { %s };' % ', '.join('%d' % v for v in thr))
    o.append('')
    mp = ptr(0x158)
    assert mp == 0x1B78A0 and u32(mp) == 4
    xs = [s16(mp + 4 + 2 * i) for i in range(4)]
    ys = [s16(mp + 4 + 8 + 2 * i) for i in range(4)]
    assert xs == [2000, 3000, 4000, 6000] and ys == [300, 200, 150, 100], (xs, ys)
    o.append("/* *(0x5713C + 0x158) = 0x1B78A0: the override's turbine -> torque map (0xB6E10), and the pedal byte")
    o.append(' * *(0x5713C + 0x154) = 0x1FE8F6 */')
    o.append('const int16_t gp_cal_ov_x[4] = { %s };' % ', '.join('%d' % v for v in xs))
    o.append('const int16_t gp_cal_ov_y[4] = { %s };' % ', '.join('%d' % v for v in ys))
    o.append('const uint8_t gp_cal_ov_ped = %du;' % img[ptr(0x154)])
    o.append('')
    o = o_main
    # the in-place addresses (cal_inplace.h) against the chains read above
    assert (ptr(0x2C), ptr(0x34)) == (0x1B607C, 0x1B6094)
    assert [ptr(x) for x in (0xF0, 0xF4, 0xF8, 0xFC)] == [0x1B69A4 + 0xD0 * k for k in range(4)]
    assert [ptr(x) for x in (0xE0, 0xE4, 0xE8, 0xEC)] == [0x1B6664 + 0xD0 * k for k in range(4)]
    assert [ptr(x) for x in (0xD0, 0xD4, 0xD8, 0xDC)] == [0x1B6324 + 0xD0 * k for k in range(4)]
    assert [ptr(x) for x in tmp_offs] == [0x1FE8EA + k for k in range(10)]
    assert (ptr(0x7C), ptr(0xA8), ptr(0x154)) == (0x1FE8E9, 0x1FE8F4, 0x1FE8F6)
    assert [ptr(x) for x in (0xB8, 0xBC, 0xC0, 0xC4, 0xC8)] == [0x1FF1FA + 2 * k for k in range(5)]
    assert mp == 0x1B78A0
    # class-1 rows
    on_rows, off_rows = [], []
    for frm in (2, 3):
        idx = u32(0x5F014 + 4 * frm)
        assert idx == frm - 2, (frm, idx)
        blk = u32(0x5CD5C + 8 * idx)
        assert blk == (0x5C84C, 0x5C894)[frm - 2]
        on_rows.append((img[u32(blk + 4)], img[u32(blk + 0x14)], img[u32(blk + 0)]))
        pidx = u32(0x5E984 + 4 * frm)
        assert pidx == 7 + (frm - 2)
        boff = u32(0x59E34 + 8 * pidx)
        assert boff == (0x596E4, 0x59718)[frm - 2]
        q = u32(boff + 0x1C)
        assert u32(q) == 4 and u32(q + 4) == 4 and not any(img[q + 16:q + 32]), 'off phase-1 map'
        maps = []
        for off in (0xC, 0x28):
            m = u32(boff + off)
            assert u32(m) == 4
            maps.append((list(img[m + 4:m + 8]), list(img[m + 8:m + 12])))
        off_rows.append(maps)
    assert on_rows == [(0, 0, 50), (0, 0, 40)], on_rows
    assert off_rows[0][0] == ([17, 42, 67, 101], [20, 20, 16, 10])
    assert off_rows[0][1] == ([34, 51, 67, 151], [7, 20, 20, 10])
    assert off_rows[1][0] == ([17, 42, 67, 101], [10, 10, 10, 10])
    assert off_rows[1][1] == ([42, 51, 84, 151], [7, 10, 20, 20])
    # ---- 2026-11-20: the PHASE-BODY tables (~/tcu_sweep/shift_phase_bodies_decode.md §1.5 / §2 / §3) ----
    # per up-shift row (variant 0 = the 0x89C06 == 0 column of every block array), the maps the on-coming
    # (UA 0x5B9B8 / UB 0x5A3DC / UC 0x5B668 class rows) and off-going (O40 0x59538 / O3C 0x58C98 /
    # O4C 0x59370 class rows) phase bodies read. Each map is copied over its exact size (the next map /
    # field pointer in the cal region confirms it, see the host test gp_cal_bytes), referenced from a
    # per-row struct. Rows beyond NUP are NOT in the image (app size budget): their bodies are counted
    # stand-ins in app/gp_shadow.c.
    NUP = int(sys.argv[3])       # up-shift rows 0..NUP-1 (1->2 .. NUP->NUP+1)
    assert 1 <= NUP <= 7
    NCLS = 2                                                  # shift classes 0 and 1 (the kind machine's two)

    def msize(t, a):
        if t == 'c8':
            return 1
        if t == 'c16':
            return 2
        if t == 'm1u8':
            return 4 + 2 * u32(a)
        if t == 'm1s16':
            return 4 + 4 * u32(a)
        if t == '2du8':
            return 8 + u32(a) + u32(a + 4) + u32(a) * u32(a + 4)
        if t == '2ds16':
            return 8 + 2 * (u32(a) + u32(a + 4) + u32(a) * u32(a + 4))
        raise AssertionError(t)

    # idx tables: 9 x 9 u32 [to*9 + from]
    IDX_T = {'ua': 0x5EC48, 'ub': 0x5ED8C, 'uc0': 0x5F158, 'uc1': 0x5F158 + 0x144, 'o40': 0x5DF64,
             'o3c': 0x5DE20, 'o4c0': 0x5E330, 'o4c1': 0x5E330 + 0x144, 'c134': 0x6113C}
    assert u32(0x5F29C) == 7 and u32(0x5E474) == 7
    BLK_T = {'ua': 0x5B9B8, 'ub': 0x5A3DC, 'uc': 0x5B668, 'o40': 0x59538, 'o3c': 0x58C98, 'o4c': 0x59370,
             'c134': 0x57434}
    FIELDS = {
        'ua': [(0x04, 'm1s16'), (0x08, 'm1s16'), (0x0C, 'm1u8'), (0x10, 'c8'), (0x14, 'c8'), (0x1C, '2ds16'),
               (0x28, 'm1s16'), (0x2C, 'm1s16'), (0x30, 'm1s16'), (0x34, 'm1s16'), (0x3C, 'm1s16'),
               (0x40, 'c16'), (0x44, 'm1s16'), (0x48, '2ds16')],
        'ub': [(0x00, 'm1s16'), (0x04, 'm1u8')],
        'uc': [(0x00, 'm1u8'), (0x04, '2du8'), (0x08, 'c8'), (0x0C, '2ds16'), (0x18, '2du8'), (0x20, 'col0'),
               (0x28, 'c8'), (0x2C, 'c8'), (0x30, '2ds16'), (0x38, '2ds16')],
        'o40': [(0x00, 'c16'), (0x04, 'col0'), (0x0C, 'c16'), (0x10, 'c8'), (0x18, '2ds16'), (0x1C, 'm1s16')],
        'o3c': [(0x08, 'm1s16')],
        'o4c': [(0x00, 'c8'), (0x04, '2du8'), (0x08, 'm1s16'), (0x0C, '2du8'), (0x10, 'm1s16')],
        'c134': [(0x04, 'c8')],
    }
    NAMES = {'ua': 'gp_ua_t', 'ub': 'gp_ub_t', 'uc': 'gp_uc_t', 'o40': 'gp_o40_t', 'o3c': 'gp_o3c_t',
             'o4c': 'gp_o4c_t', 'c134': 'gp_c134_t'}

    def msz2(t, a):
        if t == 'col0':                                       # the first x column of a 2ds16 map as a 1-D s16 map
            return 4 + 4 * u32(a + 4)
        return msize(t, a)

    for n in range(1, NUP + 1):
        for k in ('ua', 'ub', 'uc0', 'o40', 'o3c', 'o4c0', 'c134'):
            assert u32(IDX_T[k] + 4 * ((n + 1) * 9 + n)) == n - 1, (k, n)
        for k in ('uc1', 'o4c1'):
            assert u32(IDX_T[k] + 4 * ((n + 1) * 9 + n)) == 7 + n - 1, (k, n)
    maps = {}                                                 # addr -> (type, label)

    def add_row(fam, absidx):
        b = u32(BLK_T[fam] + 8 * absidx)                      # variant 0 = the first word of the pair
        mem = []
        for off, t in FIELDS[fam]:
            p = u32(b + off)
            if t not in ('c8', 'c16'):
                if p in maps:
                    assert maps[p][0] == t, (hex(p), maps[p], t)
                maps[p] = (t, 'm_%05X' % p)
            mem.append((off, t, p))
        return mem

    # UA+0x4C (the 0x1144F0 term over torque x speed) is all zero in every ported row: asserted, not copied
    for i in range(NUP):
        b = u32(BLK_T['ua'] + 8 * i)
        q = u32(b + 0x4C)
        nx, ny = u32(q), u32(q + 4)
        assert not any(img[q + 8 + 2 * (nx + ny):q + 8 + 2 * (nx + ny + nx * ny)]), ('UA+0x4C', i)
    famrows = {}
    for fam in ('ua', 'ub', 'o40', 'o3c', 'c134'):
        famrows[fam] = [add_row(fam, i) for i in range(NUP)]
    famrows['uc'] = [[add_row('uc', 7 * c + i) for i in range(NUP)] for c in range(NCLS)]
    famrows['o4c'] = [[add_row('o4c', 7 * c + i) for i in range(NUP)] for c in range(NCLS)]

    o.append('/* the mutation negative (ctest gp_shadow_neg_PHCAL): the 1->2 on-coming phase-1 delay UC+8 = 0 -> 4 passes */')
    o.append('#if defined(GP_NEG_PHCAL)')
    o.append('#define GP_NEG_PH(v) ((v) + 4u)')
    o.append('#else')
    o.append('#define GP_NEG_PH(v) (v)')
    o.append('#endif')
    o.append('')
    o.append('/* ---- the phase-body maps (2026-11-20): the cal maps of the up-shift rows 1->2 .. %d->%d, classes 0 / 1,' % (NUP, NUP + 1))
    o.append(' * variant 0; each named m_<stock flash address>; col0 = the first x column of a 2-D map as a 1-D s16')
    o.append(" * map {n = ny; y axis; z[.][0]} (the x input, the stock's ctx+0xC, is a stand-in 0 below the axis) */")
    chk = []
    for a in sorted(maps):
        t, lab = maps[a]
        if t == 'col0':
            nx, ny = u32(a), u32(a + 4)
            assert (nx, ny) == (8, 10) and u16(a + 8) >= 19, (hex(a), nx, ny)
            n = 8 + 2 * (nx + ny + nx * ny)                   # the whole 2-D map (the reader takes column 0)
        else:
            n = msize(t, a)
        assert a >= 0x80000 and a + n <= len(img), (hex(a), n)   # in place (app/cal_inplace.h)
        chk.append((a, n, 1 if t == 'col0' else 0, fnv1a(img[a:a + n])))
    o.append('/* the maps are read IN PLACE at their stock addresses (2026-11-20): the row structs hold the addresses;')
    o.append(' * col0 members point at a 2-D s16 map whose first x column the reader gathers */')
    o.append('')
    # ---- 2026-11-20 (phases2): the DOWN-SHIFT rows, class 1 (variant 0), from = 2..8 (to = from - 1) ----
    # decode shift_class_counters_decode.md section 6 numbers 2->1 / 3->2; the other pairs are the same blocks
    # of the same arrays (same field shapes asserted below; their VALUES are not decode-verified).
    NDN = 7
    DN_IDX = {'d58': (0x5F014, 0x5CD5C, 0), 'd60': (0x5F8F0, 0x5C65C, 7), 'd48': (0x5E1EC, 0x5A21C, 0),
              'd50': (0x5E984, 0x59E34, 7), 'd138': (0x61280, 0x57BCC, 0)}
    DN_F = [  # (struct member, family, offset, type)
        ('on_lock', 'd58', 0x00, 'c8'), ('on_delay', 'd58', 0x04, 'c8'), ('on_kiss', 'd58', 0x0C, 'm1s16'),
        ('on_dur0a', 'd58', 0x14, 'c8'), ('on_t5', 'd58', 0x40, 'm1s16'),
        ('on_lvl', 'd60', 0x28, '2ds16'), ('on_ex0c', 'd60', 0x2C, 'm1u8'),
        ('fin', 'd138', 0x08, 'c8'),
        ('of_pct', 'd48', 0x0C, 'm1u8'), ('of_thr', 'd48', 0x10, 'm1u8'), ('of_t0a', 'd48', 0x1C, '2ds16'),
        ('of_slip', 'd50', 0x00, 'm1s16'), ('of_d0b', 'd50', 0x0C, 'm1u8'), ('of_p1', 'd50', 0x14, '2du8'),
        ('of_d1', 'd50', 0x1C, '2du8'), ('of_d0f', 'd50', 0x28, 'm1u8'), ('of_l0d', 'd50', 0x2C, '2ds16'),
    ]
    dn_rows = []
    dn_maps = {}
    for frm in range(2, 2 + NDN):
        blks = {}
        for fam, (idxt, arr, base) in DN_IDX.items():
            idx = u32(idxt + 4 * frm)
            assert idx == base + frm - 2, (fam, frm, idx)
            blks[fam] = u32(arr + 8 * idx)
        row = []
        for name, fam, off, t in DN_F:
            p = u32(blks[fam] + off)
            if t == 'c8':
                row.append((name, t, p, img[p]))
                continue
            n = msize(t, p)
            assert p >= 0x80000 and p + n <= len(img), (name, hex(p))
            dn_maps[p] = (t, n)
            row.append((name, t, p, None))
        dn_rows.append((frm, row))
    # the maps do not overlap (contiguous cal layout, 4-byte alignment padding between them)
    srt = sorted(dn_maps)
    for i, a in enumerate(srt[:-1]):
        t, n = dn_maps[a]
        assert srt[i + 1] >= a + n, (hex(a), n, hex(srt[i + 1]))
    # the class-1 numbers of the decode (the in-place data against its section 6 table)
    r2, r3 = dn_rows[0][1], dn_rows[1][1]
    g = lambda r, nm: [x for x in r if x[0] == nm][0]
    assert (g(r2, 'on_lock')[3], g(r3, 'on_lock')[3]) == (50, 40)
    assert (g(r2, 'on_delay')[3], g(r3, 'on_delay')[3], g(r2, 'on_dur0a')[3], g(r3, 'on_dur0a')[3]) == (0, 0, 0, 0)
    assert (g(r2, 'fin')[3], g(r3, 'fin')[3]) == (1, 1)
    assert list(img[g(r2, 'of_d0b')[2] + 4:g(r2, 'of_d0b')[2] + 12]) == [17, 42, 67, 101, 20, 20, 16, 10]
    assert list(img[g(r2, 'of_d0f')[2] + 4:g(r2, 'of_d0f')[2] + 12]) == [34, 51, 67, 151, 7, 20, 20, 10]
    assert list(img[g(r3, 'of_d0b')[2] + 4:g(r3, 'of_d0b')[2] + 12]) == [17, 42, 67, 101, 10, 10, 10, 10]
    assert list(img[g(r3, 'of_d0f')[2] + 4:g(r3, 'of_d0f')[2] + 12]) == [42, 51, 84, 151, 7, 10, 20, 20]
    for a in sorted(dn_maps):
        t, n = dn_maps[a]
        chk.append((a, n, 0, fnv1a(img[a:a + n])))


    hh = ['/* gp_cal_ph.h - GENERATED by tools/gen_gp_cal.py (the phase-body row structs); do not edit.',
          ' * member f<off> = the stock cal block + <off>: a cell value or the flash ADDRESS of its map (read in place, app/cal_inplace.h). */',
          '#ifndef TCU_APP_GP_CAL_PH_H', '#define TCU_APP_GP_CAL_PH_H', '#include <stdint.h>', '',
          '#define GP_PH_NUP %du' % NUP, '']
    for fam in ('ua', 'ub', 'uc', 'o40', 'o3c', 'o4c', 'c134'):
        ms = []
        for off, t in FIELDS[fam]:
            ty = {'c8': 'uint8_t', 'c16': 'int16_t'}.get(t, 'uint32_t')
            ms.append('%s f%02x;' % (ty, off))
        hh.append('typedef struct { %s } %s;' % (' '.join(ms), NAMES[fam]))
        hh.append('extern const %s gp_ph_%s%s;' % (NAMES[fam], fam, '[2][GP_PH_NUP]' if fam in ('uc', 'o4c') else '[GP_PH_NUP]'))
    hh += ['', '#define GP_DN_N %du' % NDN,
           '/* the class-1 single down-shift rows, from = 2..8 (index from - 2): the cell values and the flash ADDRESSES of the maps */',
           'typedef struct { %s } gp_dn_t;' % ' '.join(('uint8_t %s;' if t == 'c8' else 'uint32_t %s;') % nm for nm, fam, off, t in DN_F),
           'extern const gp_dn_t gp_ph_dn[GP_DN_N];']
    hh += ['', 'typedef struct { uint32_t addr; uint32_t len; uint32_t col0; uint32_t fnv; } gp_ph_chk_t;',
           '#if defined(GP_CAL_CHECK)', 'extern const gp_ph_chk_t gp_ph_chk[];', 'extern const unsigned gp_ph_chk_n;', '#endif',
           'extern const unsigned gp_ph_nup;', '', '#endif']
    open(sys.argv[4], 'w').write('\n'.join(hh) + '\n')


    def init_row(mem, neg=False):
        parts = []
        for off, t, p in mem:
            if t == 'c8' and neg and off == 0x08:
                parts.append('GP_NEG_PH(%du)' % img[p])      # the mutation negative: the phase-1 delay
            elif t == 'c8':
                parts.append('%du' % img[p])
            elif t == 'c16':
                parts.append('%d' % struct.unpack('>h', img[p:p + 2])[0])
            else:
                parts.append('0x%06Xu' % p)
        return '{ %s }' % ', '.join(parts)

    for fam in ('ua', 'ub', 'o40', 'o3c', 'c134'):
        o.append('const %s gp_ph_%s[GP_PH_NUP] = {' % (NAMES[fam], fam))
        for r in famrows[fam]:
            o.append('    %s,' % init_row(r))
        o.append('};')
    for fam in ('uc', 'o4c'):
        o.append('const %s gp_ph_%s[2][GP_PH_NUP] = {' % (NAMES[fam], fam))
        for c in range(NCLS):
            o.append('    {')
            for ri, r in enumerate(famrows[fam][c]):
                o.append('        %s,' % init_row(r, fam == 'uc' and ri == 0))
            o.append('    },')
        o.append('};')
    o.append('/* the class-1 single down-shift rows (from = 2..8): cells + map addresses (read in place) */')
    o.append('const gp_dn_t gp_ph_dn[GP_DN_N] = {')
    for frm, row in dn_rows:
        o.append('    { %s },  /* %d->%d */' % (', '.join(('%du' % v) if t == 'c8' else ('0x%06Xu' % p) for nm, t, p, v in row), frm, frm - 1))
    o.append('};')
    o.append('')
    o.append('#if defined(GP_CAL_CHECK)')
    o.append('/* the host check: stock address, length, col0, FNV-1a of the stock bytes */')
    o.append('const gp_ph_chk_t gp_ph_chk[] = {')
    for a, n, c0, h in chk:
        o.append('    { 0x%06Xu, %du, %du, 0x%08Xu },' % (a, n, c0, h))
    o.append('};')
    o.append('const unsigned gp_ph_chk_n = %du;' % len(chk))
    o.append('#endif')
    o.append('')
    o.append('const unsigned gp_ph_nup = GP_PH_NUP;')
    o.append('')
    # the sync-rate DT1 time constant map *(0x5713C + 0x28) = 0x1B606C {u32 n; u16 x[n]; u16 y[n]} (0x1179D8 -> 0xD2058)
    dp = ptr(0x28)
    assert dp == 0x1B606C and u32(dp) == 3
    o.append('/* the DT1 time constant of the sync rate: *(0x5713C + 0x28) = 0x1B606C over the output speed 0x89C08 (0xB6EAE) */')
    o.append('const uint16_t gp_cal_dt1x[3] = { %s };' % ', '.join('%du' % u16(dp + 4 + 2 * i) for i in range(3)))
    o.append('const uint16_t gp_cal_dt1y[3] = { %s };' % ', '.join('%du' % u16(dp + 10 + 2 * i) for i in range(3)))
    o.append('')

    open(sys.argv[2], 'w').write('\n'.join(o))


