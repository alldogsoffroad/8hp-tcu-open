#!/usr/bin/env python3
"""gen_gp_cal.py — THE GEAR-PAIR SHIFT-ENGINE SHADOW: emit firmware/app/gp_cal.c,
the typed const copies of the stock tables the read-only gear-pair shadow
(app/gp_shadow.c) uses. Every object carries its stock flash address; the host
test gp_cal_bytes (tests/unit/test_gp_shadow.c --cal) re-reads the image and
compares value for value.

Roots (~/tcu_sweep/shift_engine_gearpair_decode.md §1.2 / §1.6 / §1.4 and
~/tcu_sweep/gp_shadow_port.md; each address read in the bytes):
  0x5061C  the on-coming element of a gear pair, t[(from+1) + (to+1)*10]
           (0xDC198 via 0xB852A, pool 0xDC3DC), element 1..5 = A..E
  0x50680  the off-going element, same index (0xDC1AE via 0xB853C, pool 0xDC3E0)
  0x6315C  BD17 = t[BD1E*3 + BD16] (0xED988, pool 0xEDB44)
  0x5EC24  the on-coming phase sequence, phase = t[step*3 + type] (0x113D0A,
           pool 0x113D98), steps 0..11
  0x63555  the off-going phase sequence, phase = t[step*3 + type] (0x110ADE,
           pool 0x110B84), steps 0..12
  0x4FAA4  the gear ratios x1000 (0xD7C8C: *0xFFF84B2C, gs_engine.c)
  *(0x5713C + 0xB0) = 0x1FF1F6  the synchronisation band, rpm (0xEB4A4 /
           0x117F48, gs_engine.c)
The direct-shift type 0x4F9DC and the kind 0x4FA40 are sm_cal_gtype /
sm_cal_gkind (app/sm_cal.c, already byte-checked).

usage: gen_gp_cal.py <stock image> <out .c>
"""
import struct
import sys

T_ON, T_OFF, T_BD17, T_ONSEQ, T_OFFSEQ, T_RATIO = 0x5061C, 0x50680, 0x6315C, 0x5EC24, 0x63555, 0x4FAA4
N_ONSEQ, N_OFFSEQ = 12 * 3, 13 * 3


def main():
    img = open(sys.argv[1], 'rb').read()
    u32 = lambda a: struct.unpack('>I', img[a:a + 4])[0]
    u16 = lambda a: struct.unpack('>H', img[a:a + 2])[0]
    # the pools (each read in the bytes; the host test re-checks the values)
    assert u32(0xDC3DC) == T_ON and u32(0xDC3E0) == T_OFF
    assert u32(0xEDB44) == T_BD17
    assert u32(0x113D98) == T_ONSEQ and u32(0x110B84) == T_OFFSEQ
    thr_at = u32(0x5713C + 0xB0)
    assert thr_at == 0x1FF1F6, hex(thr_at)

    o = []
    o.append('/* gp_cal.c — GENERATED by tools/gen_gp_cal.py from the stock image; do not edit.')
    o.append(' * The gear-pair shadow\'s tables (app/gp_cal.h); byte-checked by')
    o.append(' * tests/unit/test_gp_shadow.c --cal (ctest gp_cal_bytes). */')
    o.append('#include "app/gp_cal.h"')
    o.append('')
    o.append('/* the mutation negative (ctest gp_shadow_neg_TABLE): the 1->2 on-coming element,')
    o.append(' * t[(1+1) + (2+1)*10] = 5 (E) -> 4 (D) — the pre-select / commit check must fail */')
    o.append('#if defined(GP_NEG_TABLE)')
    o.append('#define GP_NEG_E(v) ((v) - 1u)')
    o.append('#else')
    o.append('#define GP_NEG_E(v) (v)')
    o.append('#endif')
    o.append('')

    def u8arr(name, addr, n, comment, neg=None):
        vals = ['%du' % b for b in img[addr:addr + n]]
        if neg is not None:
            i, macro, want = neg
            assert img[addr + i] == want, (name, i, img[addr + i])
            vals[i] = '%s(%du)' % (macro, want)
        o.append('/* %s */' % comment)
        o.append('const uint8_t %s[%d] = {' % (name, n))
        for i in range(0, n, 12):
            o.append('    %s,' % ', '.join(vals[i:i + 12]))
        o.append('};')
        o.append('')

    u8arr('gp_cal_on', T_ON, 100, '0x5061C: the on-coming element t[(from+1) + (to+1)*10] (0xDC198)',
          ((1 + 1) + (2 + 1) * 10, 'GP_NEG_E', 5))
    u8arr('gp_cal_off', T_OFF, 100, '0x50680: the off-going element t[(from+1) + (to+1)*10] (0xDC1AE)')
    u8arr('gp_cal_bd17', T_BD17, 9, '0x6315C: BD17 = t[BD1E*3 + BD16] (0xED988)')
    u8arr('gp_cal_onseq', T_ONSEQ, N_ONSEQ, '0x5EC24: the on-coming phase t[step*3 + type] (0x113D0A)')
    u8arr('gp_cal_offseq', T_OFFSEQ, N_OFFSEQ, '0x63555: the off-going phase t[step*3 + type] (0x110ADE)')
    o.append('/* 0x4FAA4: the gear ratios x1000, gear -1..8 (0xD7C8C) */')
    o.append('const uint16_t gp_cal_ratio[10] = { %s };' % ', '.join('%du' % u16(T_RATIO + 2 * i) for i in range(10)))
    o.append('')
    o.append('/* *(0x5713C + 0xB0) = 0x1FF1F6: the synchronisation band, rpm (0x117F48) */')
    o.append('const uint16_t gp_cal_sync_thr = %du;' % u16(thr_at))
    o.append('')
    open(sys.argv[2], 'w').write('\n'.join(o))


if __name__ == '__main__':
    main()
