#!/usr/bin/env python3
"""gen_rq_fill_cal.py — M5-1: emit firmware/app/rq_fill_cal.c, the const copies
of the stock flash bytes the element fill machinery reads (the request
objects' calibration blocks, the actuator curve / correction maps, the
per-unit curves, the scalar calibration cells and the ROM pointer tables).

The firmware reads them by their STOCK flash address (rq_fill.c rqf_fl*),
so the ported code follows the stock's own pointer chains. The host test
m5fill --stock compares every blob with the image byte for byte.

usage: gen_rq_fill_cal.py <stock image> <out .c>
"""
import sys

# (start, end) flash ranges, end exclusive. Each is justified in rq_fill.c.
RANGES = [
    (0x0000E004, 0x0000E2B6),  # per-unit curves 0xE004..0xE13C (7 × 0x34) + correction maps 0xE170 / 0xE214
    (0x00053F38, 0x00053F3C),  # 0xFFF84CFC → 0x53F38 (Sys / WK curves; not read here, kept for the pointer test)
    (0x00054C4C, 0x00054FE0),  # 0xFFF84D14 / D18 / D1C / D20..D30 → the actuator and element calibration tables
    (0x001A82E0, 0x001AAB84),  # every map those tables point into (actuator + elements A..E)
    (0x001FE82B, 0x001FE83E),  # u8 scalars (G +0x24/+0x28/+0x3C, element +0x48/+0x8C/+0x9C)
    (0x001FEF6C, 0x001FEF70),  # i_min / i_max 500 / 8500 (0x537F8 → 0x1FEF6C)
    (0x001FF082, 0x001FF0A6),  # u16 scalars (G +0x14/+0x18/+0x1C, element +0x50/+0x68/+0x98)
]


def main():
    img = open(sys.argv[1], 'rb').read()
    out = []
    out.append('/* rq_fill_cal.c — GENERATED by tools/gen_rq_fill_cal.py from the pristine')
    out.append(' * stock image (260924131233 1034420267_IFla.bin). Do not edit: regenerate.')
    out.append(' * Const copies of the stock flash ranges the M5-1 element fill reads, by')
    out.append(' * flash address (rq_fill.c rqf_fl*). The host test m5_fill_bytes compares')
    out.append(' * every byte with the image. */')
    out.append('#include "app/rq_fill.h"')
    out.append('')
    out.append('#if !defined(TCU_RAM_APP)')
    names = []
    for (a, b) in RANGES:
        n = 'RQF_FL_%06X' % a
        names.append((n, a, b))
        out.append('static const uint8_t %s[0x%X] = {' % (n, b - a))
        data = img[a:b]
        for i in range(0, len(data), 16):
            out.append('    ' + ', '.join('0x%02X' % x for x in data[i:i + 16]) + ',')
        out.append('};')
    out.append('')
    out.append('const rqf_blob_t RQF_BLOBS[RQF_NBLOBS] = {')
    for (n, a, b) in names:
        out.append('    { 0x%08Xu, 0x%Xu, %s },' % (a, b - a, n))
    out.append('};')
    out.append('#endif')
    out.append('')
    open(sys.argv[2], 'w').write('\n'.join(out))
    print('blobs: %d, bytes: %d' % (len(RANGES), sum(b - a for a, b in RANGES)))


if __name__ == '__main__':
    main()
