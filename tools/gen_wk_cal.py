#!/usr/bin/env python3
"""gen_wk_cal.py - writes app/wk_cal.c: the stock constants the READ-ONLY torque-converter
lock-up (WK) shadow (app/wk_shadow.c) reads from BELOW 0x80000 (our application overwrites that
region): the per-unit WK current curve 0xE13C and the normally-closed temperature map 0xE214
(both EOL data in the image, reached through the per-unit pointer tables 0xFFF8CDFC / 0xFFF8CDEC,
all valid flags 1 in the dump). Usage: gen_wk_cal.py IMAGE OUT.c
The host test `wk_cal_bytes` re-derives every table from the image and compares."""
import struct
import sys

img = open(sys.argv[1], 'rb').read()


def u32(a):
    return struct.unpack('>I', img[a:a + 4])[0]


def u16(a):
    return struct.unpack('>H', img[a:a + 2])[0]


def s16(a):
    return struct.unpack('>h', img[a:a + 2])[0]


out = []
w = out.append
w('/* wk_cal.c - GENERATED by tools/gen_wk_cal.py from the stock image (do not edit).\n'
  ' * The stock calibration the lock-up shadow reads from BELOW 0x80000. */\n')
w('#include "app/wk_cal.h"\n')
# the WK curve 0xE13C: {u32 n; u16 x[n]; u16 y[n]}
n = u32(0xE13C)
assert n == 12
w('const uint16_t WK_E13C[1 + 2 * 12] = { %d, ' % n + ', '.join(str(u16(0xE13C + 4 + 2 * i)) for i in range(2 * n)) + ' };')
# the NC temperature map 0xE214: {u32 nx; u32 ny; s16 x[nx]; s16 y[ny]; s16 z[ny][nx]}
nx, ny = u32(0xE214), u32(0xE214 + 4)
assert (nx, ny) == (12, 5)
vals = [s16(0xE214 + 8 + 2 * i) for i in range(nx + ny + nx * ny)]
w('const int16_t WK_E214[2 + 12 + 5 + 60] = { %d, %d, ' % (nx, ny) + ', '.join(str(v) for v in vals) + ' };')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
