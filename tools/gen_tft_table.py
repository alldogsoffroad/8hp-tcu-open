#!/usr/bin/env python3
"""Generate firmware/io/sensors/tft_table.h: transmission fluid temperature versus the ratio
R_sensor / R_sense measured by the AN8/AN1 pair (spec 04 section 4.1).

Circuit (spec 04, M2 analysis): 5 V -> pull-up -> AN8 -> NTC sensor -> AN1 -> sense resistor -> 0 V.
The firmware measures r = (AN8 - AN1) / AN1 = R_sensor / R_sense, independent of the 5 V supply
and of the pull-up. Temperature follows the Steinhart-Hart equation

    1/T = A + B ln(r) + C ln(r)^3        (T in kelvin)

PROVISIONAL coefficients: fitted to the shape of the stock behaviour (pull-up / sense ratio 10.41,
maximum deviation 3.4 degC over -40..170 degC). The table is the project's own; it is not the
stock calibration curve. Replace the coefficients with values from the sensor datasheet or a
bench measurement against a reference thermometer before relying on it.

Usage: gen_tft_table.py <output.h>
"""
import math
import sys

A, B, C = 0.0025741033603174615, 0.00023246820880269405, 6.646514418934992e-06
T_MIN, T_MAX, STEP = -50, 180, 5


def ratio_at(t_c):
    """Solve the Steinhart-Hart equation for r at temperature t_c (bisection on ln r)."""
    target = 1.0 / (t_c + 273.15)
    lo, hi = -8.0, 12.0                      # ln r; 1/T falls as ln r rises
    for _ in range(200):
        mid = (lo + hi) / 2
        if A + B * mid + C * mid ** 3 > target:
            hi = mid
        else:
            lo = mid
    return math.exp((lo + hi) / 2)


def main():
    rows = [(round(ratio_at(t) * 1000), t * 10) for t in range(T_MIN, T_MAX + 1, STEP)]
    L = ["/* GENERATED by tools/gen_tft_table.py - do not edit. PROVISIONAL sensor model, see the",
         " * generator. Ratio R_sensor/R_sense in 1/1000 (falling), temperature in 0.1 degC. */",
         "#ifndef TCU_TFT_TABLE_H", "#define TCU_TFT_TABLE_H", "",
         "#include <stdint.h>", "",
         f"#define TFT_TABLE_N {len(rows)}u", "",
         "static const struct { uint32_t ratio_milli; int16_t degc10; } tft_table[TFT_TABLE_N] = {"]
    for r, t in rows:
        L.append(f"    {{ {r:7d}u, {t:5d} }},")
    L += ["};", "", "#endif"]
    open(sys.argv[1], "w").write("\n".join(L) + "\n")
    print(f"{len(rows)} points, ratio {rows[0][0]} .. {rows[-1][0]} -> {sys.argv[1]}")


if __name__ == "__main__":
    main()
