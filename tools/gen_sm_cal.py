#!/usr/bin/env python3
"""gen_sm_cal.py — THE SHIFT-MAP SHADOW: emit firmware/app/sm_cal.c, the typed
const copies of the stock calibration the read-only shift-target shadow
(app/sm_shadow.c) uses. Every object carries its stock flash address; the host
test sm_cal_bytes (tests/unit/test_sm_shadow.c --cal) re-reads the image and
compares value for value.

Roots (~/tcu_sweep/shift_map_decode.md, ~/tcu_sweep/sm_shadow_port.md; each
indirection is the stock's own, read in the bytes):
  *0xFFF84EB0 = 0x62278   the shift-map pointer table (0x1290A8: id k < 25 ->
                          @(20*(k%5) + 4*(k/5)); the remap 0x1F3B7C only ever
                          yields k in {0, 5, 10, 15, 20} for level <= 4 and
                          base <= 4, i.e. @0, @4, @8, @12, @16 = the five
                          base-0 maps 0x1E9910 / 0x1E9A9C / 0x1E9C28 /
                          0x1E9DB4 / 0x1E9F40, each {u32 nx, u32 ny, u16
                          xa[nx], u16 ya[ny], u16 z[ny][nx]}, 14 x 12)
  (*0xFFF84EB0)+0x1A4 = 0x1F3B7C  the program-id remap {u32 n = 100, u8[n]}
  **0xFFF84EB4 = 0x1F3BE4  the program priority table {u32 n1 = 18, u32 n2 =
                          14, u8 t[p + col*18]} (0x123990 via 0x1214B4)
  (*0xFFF84E60)+0x0C = 0x1E5E44  the step limits {u32 63, u32 2, u8 t[col +
                          dir*63]} (0xFC358 via 0x1214B4, col = program - 1)
  (*0xFFF84E60)+0x00 = 0x1E5E30  the minimum-gear-by-speed curve {u32 n = 8,
                          u16 v[n]} (0xFC112 via 0x121482)
  (*0xFFF84E44)+0x0C / +0x10 = 0x1FEC8C / 0x1FEC8D  the AB30 filter weights
                          (0xF9570 -> 0x121BCC)

  (2026-11-19) the gear feedback chain: the gear-pair tables 0x4F6A4 /
                          0x4F9DC / 0x4FA40 / 0x4F708 and the six speed-limit
                          tables of *0xFFF84C80 (ROM init DTBL 0x65110 + 0xC80
                          = 0x53610 -> 0x19AB78 .. 0x19AF88)

usage: gen_sm_cal.py <stock image> <out .c>
"""
import struct
import sys


def main():
    img = open(sys.argv[1], 'rb').read()
    u32 = lambda a: struct.unpack('>I', img[a:a + 4])[0]
    u16 = lambda a: struct.unpack('>H', img[a:a + 2])[0]

    ptab = 0x62278
    maps = []
    for k in range(5):
        p = u32(ptab + 4 * k)
        nx, ny = u32(p), u32(p + 4)
        assert (nx, ny) == (14, 12), (hex(p), nx, ny)
        xa = [u16(p + 8 + 2 * i) for i in range(nx)]
        ya = [u16(p + 8 + 2 * nx + 2 * i) for i in range(ny)]
        z = [u16(p + 8 + 2 * nx + 2 * ny + 2 * i) for i in range(nx * ny)]
        maps.append((p, nx, ny, xa, ya, z))

    remap = 0x1F3B7C
    prio = 0x1F3BE4
    step = 0x1E5E44
    mg = 0x1E5E30
    assert u32(remap) == 100 and u32(prio) == 18 and u32(prio + 4) == 14
    assert u32(step) == 63 and u32(step + 4) == 2 and u32(mg) == 8
    # the indirections, checked here and again by the host test
    assert u32(0x61D34 + 0x0C) == step and u32(0x61D34) == mg

    o = []
    o.append('/* sm_cal.c — GENERATED by tools/gen_sm_cal.py from the stock image; do not edit.')
    o.append(' * The shift-map shadow\'s calibration (app/sm_cal.h); byte-checked by')
    o.append(' * tests/unit/test_sm_shadow.c --cal (ctest sm_cal_bytes). */')
    o.append('#include "app/sm_cal.h"')
    o.append('')
    o.append('/* the mutation negative (ctest sm_shadow_neg_MAP): map 1 (0x1E9A9C), line 8')
    o.append(' * (down 2->1) at pedal 18, 125 -> 126 — the dump cell S+0xDA must break */')
    o.append('#if defined(SM_NEG_MAP)')
    o.append('#define SM_NEG_Z(v) ((v) + 1u)')
    o.append('#else')
    o.append('#define SM_NEG_Z(v) (v)')
    o.append('#endif')
    o.append('')
    o.append('const sm_map_t sm_cal_map[SM_CAL_NMAP] = {')
    for mi, (p, nx, ny, xa, ya, z) in enumerate(maps):
        o.append('    { 0x%06Xu, %du, %du,' % (p, nx, ny))
        o.append('      { %s },' % ', '.join('%du' % v for v in xa))
        o.append('      { %s },' % ', '.join('%du' % v for v in ya))
        o.append('      {')
        for j in range(ny):
            row = ['%du' % v for v in z[j * nx:(j + 1) * nx]]
            if mi == 1 and j == 0:
                assert z[7] == 125
                row[7] = 'SM_NEG_Z(125u)'
            o.append('        %s,' % ', '.join(row))
        o.append('      } },')
    o.append('};')
    o.append('')

    def bytes_arr(name, addr, n, comment):
        vals = img[addr:addr + n]
        o.append('/* %s */' % comment)
        o.append('const uint8_t %s[%d] = {' % (name, n))
        for i in range(0, n, 18):
            o.append('    %s,' % ', '.join('%du' % b for b in vals[i:i + 18]))
        o.append('};')
        o.append('')

    bytes_arr('sm_cal_remap', remap + 4, 100, '0x1F3B80: the program-id remap (0x121432)')
    bytes_arr('sm_cal_prio', prio + 8, 18 * 14, '0x1F3BEC: the program priority table, t[p + col*18] (0x123990)')
    bytes_arr('sm_cal_step', step + 8, 63 * 2, '0x1E5E4C: the step limits, t[program-1 + dir*63] (0xFC358)')
    o.append('/* 0x1E5E34: the minimum gear by output speed (0xFC112), output rpm */')
    o.append('const uint16_t sm_cal_mingear[8] = { %s };' %
             ', '.join('%du' % u16(mg + 4 + 2 * i) for i in range(8)))
    o.append('')
    o.append('/* 0x1FEC8C / 0x1FEC8D: the AB30 output-speed filter weights (0xF9570 -> 0x121BCC) */')
    o.append('const uint8_t sm_cal_ab30w[2] = { %du, %du };' % (img[0x1FEC8C], img[0x1FEC8D]))
    o.append('')
    # the gear feedback chain (app/sm_gear.c; ~/tcu_sweep/gear_feedback_shadow_port.md)
    def s8arr(name, addr, comment, neg=None):
        vals = ['%d' % (b - 256 if b > 127 else b) for b in img[addr:addr + 100]]
        if neg is not None:
            i, macro, want = neg
            assert vals[i] == '%d' % want, (name, i, vals[i])
            vals[i] = '%s(%d)' % (macro, want)
        o.append('/* %s */' % comment)
        o.append('const int8_t %s[100] = {' % name)
        for i in range(0, 100, 10):
            o.append('    %s,' % ', '.join(vals[i:i + 10]))
        o.append('};')
        o.append('')
    o.append('/* the mutation negative (ctest sm_gear_neg_GNEXT): the next gear from 1st')
    o.append(' * toward 2nd, t[(2+1) + (1+1)*10] = 2 -> 1 — the ramp must stick in 1st */')
    o.append('#if defined(SM_NEG_GNEXT)')
    o.append('#define SM_NEG_GN(v) ((v) - 1)')
    o.append('#else')
    o.append('#define SM_NEG_GN(v) (v)')
    o.append('#endif')
    o.append('')
    s8arr('sm_cal_gnext', 0x4F6A4, '0x4F6A4: the next commanded gear t[(to+1) + (from+1)*10] (0xD1990, pool 0xD1B54)',
          (23, 'SM_NEG_GN', 2))
    s8arr('sm_cal_gtype', 0x4F9DC, '0x4F9DC: 0xB7C02 = 0xD4F86 (pool 0xD51D0)')
    s8arr('sm_cal_gkind', 0x4FA40, '0x4FA40: 0xB7C14 = 0xD4FA0 (pool 0xD51D4)')
    s8arr('sm_cal_gskip', 0x4F708, '0x4F708: 0xD16BA / 0xD1854 (pools 0xD17D0 / 0xD1970)')
    dtbl = 0x65110 + (0xFFF84C80 - 0xFFF84000)
    root = u32(dtbl)
    assert root == 0x53610, hex(root)
    tabs = [u32(root + 4 * i) for i in range(6)]
    for t in tabs:
        assert (u32(t), u32(t + 4)) == (10, 10), hex(t)
    o.append('/* *0xFFF84C80 = 0x%05X (DTBL 0x%05X): the six 10 x 10 tables */' % (root, dtbl))
    o.append('const uint32_t sm_cal_gspd_addr[6] = { %s };' % ', '.join('0x%06Xu' % t for t in tabs))
    o.append('const int16_t sm_cal_gspd[5][100] = {')
    for t in tabs[:5]:
        vals = [struct.unpack('>h', img[t + 8 + 2 * i:t + 10 + 2 * i])[0] for i in range(100)]
        o.append('    {')
        for i in range(0, 100, 10):
            o.append('        %s,' % ', '.join('%d' % v for v in vals[i:i + 10]))
        o.append('    },')
    o.append('};')
    o.append('const uint8_t sm_cal_gtemp[100] = {')
    t = tabs[5]
    for i in range(0, 100, 10):
        o.append('    %s,' % ', '.join('%du' % b for b in img[t + 8 + i:t + 18 + i]))
    o.append('};')
    o.append('')
    open(sys.argv[2], 'w').write('\n'.join(o))


if __name__ == '__main__':
    main()
