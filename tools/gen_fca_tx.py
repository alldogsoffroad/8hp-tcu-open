#!/usr/bin/env python3
"""Generate firmware/io/vehicle/fca_tx_fields.h from 1034420267_can_tx_signals.csv (spec 08).

One entry per transmitted field: message, start byte, most significant bit within that byte,
length. Rolling-counter and CRC fields are left out (added by the transmit layer).

Usage: gen_fca_tx.py <can_tx_signals.csv> <output.h>
"""
import csv
import re
import sys


def parse(row):
    pos, first, length = row["position"], int(row["first_byte"]), int(row["length_bits"])
    if "rolling counter" in pos or "CRC" in pos:
        return None
    m = re.match(r"big-endian: byte (\d+) bits (\d+)\.\.0 \(high\)", pos)
    if m:
        return int(m.group(1)), int(m.group(2)), length
    m = re.match(r"big-endian: byte (\d+) \(high\)", pos)
    if m:
        return int(m.group(1)), 7, length
    m = re.match(r"bits (\d+)\.\.(\d+)$", pos)
    if m:
        msb, lsb = int(m.group(1)), int(m.group(2))
        if msb - lsb + 1 != length:
            raise ValueError(f"length mismatch: {row}")
        return first, msb, length
    m = re.match(r"bit (\d+)$", pos)
    if m:
        return first, int(m.group(1)), 1
    raise ValueError(f"unrecognised position: {pos!r}")


def main():
    src, out = sys.argv[1], sys.argv[2]
    msgs, fields = [], []
    for row in csv.DictReader(open(src)):
        cid = int(row["can_id"], 16)
        if cid not in [m[0] for m in msgs]:
            msgs.append((cid, int(row["dlc"]), int(row["period_raw"]),
                         row["crc8"] == "yes", row["counter"] == "yes"))
        f = parse(row)
        if f:
            fields.append((cid,) + f + (row["source"],))
    fields.sort(key=lambda f: (f[0], f[1], -f[2]))

    L = []
    L.append("/* GENERATED by tools/gen_fca_tx.py from 1034420267_can_tx_signals.csv - do not edit.")
    L.append(" * Transmit field layouts of the stock TCU (spec 08). Meanings are open; see the CSV")
    L.append(" * column 'source' for the stock routine that writes each field. */")
    L.append("#ifndef TCU_FCA_TX_FIELDS_H")
    L.append("#define TCU_FCA_TX_FIELDS_H")
    L.append("")
    L.append("/* Messages: id, DLC, period (stock raw x 10 ms [I]), CRC-8, rolling counter. */")
    L.append("#define FCA_TX_MESSAGES(X) \\")
    for i, (cid, dlc, per, crc, ctr) in enumerate(msgs):
        end = " \\" if i < len(msgs) - 1 else ""
        L.append(f"    X(M_{cid:03X}, 0x{cid:03X}u, {dlc}u, {per * 10}u, {'true' if crc else 'false'}, "
                 f"{'true' if ctr else 'false'}){end}")
    L.append("")
    L.append("/* Fields: name, message, start byte, most significant bit, length in bits. */")
    L.append("#define FCA_TX_FIELDS(X) \\")
    for i, (cid, byte, msb, ln, srcfn) in enumerate(fields):
        end = " \\" if i < len(fields) - 1 else ""
        L.append(f"    X(F_{cid:03X}_B{byte}_{msb}, M_{cid:03X}, {byte}u, {msb}u, {ln}u){end}")
    L.append("")
    L.append("#endif")
    open(out, "w").write("\n".join(L) + "\n")
    print(f"{len(msgs)} messages, {len(fields)} fields -> {out}")


if __name__ == "__main__":
    main()
